// NDA de participantes (nov 2026, ver docs/nda.md). El DDL declarativo ya vive en schema.sql (generado por generate.py, ver EXTRA_TABLES: NdaEnvios y NdaEventos); este script hace el CREATE real
// sobre la base ya existente, con los índices, la bitácora que no se puede editar (un trigger rechaza UPDATE, DELETE y TRUNCATE sobre nda_eventos) y el bucket privado de Storage donde viven
// los PDF firmados. Solo agrega: no toca ninguna tabla existente. Idempotente. No se ejecuta solo.
//
// Hay que correrlo ANTES de desplegar el código del NDA con firma (el botón «NDA» consulta estas tablas). Si el código sale antes, el botón avisa que faltan las tablas y no manda nada.
//
// Uso: cd server && npx tsx --env-file=../.env scripts/add-nda-tables.ts
import { pool } from '../compat/db';
import { getSupabaseAdmin } from '../supabaseAdmin';

export const BUCKET = process.env.NDA_BUCKET ?? 'nda';

/** Los tipos de evento de la bitácora. `rebotado` y `copia_rebotada` (nov 2026): un correo del NDA que el servidor de la persona devolvió (ver src/serverUtils/nda/rebotes.ts). */
const TIPOS_DE_EVENTO = ['enviado', 'reenviado', 'abierto', 'firmado', 'rechazado', 'copia_enviada', 'copia_fallida', 'pdf_creado', 'pdf_fallido', 'rebotado', 'copia_rebotada'];
const CHECK_TIPO = `check ("tipo" in (${TIPOS_DE_EVENTO.map((t) => `'${t}'`).join(', ')}))`;

/** Todo el SQL, en orden. Se exporta para que la prueba (server/scripts/test-nda.ts) aplique exactamente lo mismo. */
export const SQL_NDA: string[] = [
  `create table if not exists nda_envios (
    id                 uuid primary key default gen_random_uuid(),
    n                  bigint generated by default as identity,
    token              text,
    recruitment_row_id uuid,
    project_code       text,
    board_id           text,
    nombre             text,
    correo             text,
    estado             text,
    enviado_at         timestamptz,
    ultimo_envio_at    timestamptz,
    envios             integer,
    abierto_at         timestamptz,
    firmado_at         timestamptz,
    rechazado_at       timestamptz,
    motivo_rechazo     text,
    nombre_firmado     text,
    texto_version      text,
    texto_hash         text,
    firma_png          text,
    pdf_path           text,
    pdf_hash           text,
    pdf_at             timestamptz,
    ip                 text,
    user_agent         text,
    enviado_por        text,
    sesion_at          timestamptz,
    sesion_lugar       text,
    sesion_texto       text,
    created_at         timestamptz not null default now(),
    updated_at         timestamptz not null default now(),
    constraint nda_envios_estado_chk check ("estado" in ('enviado', 'abierto', 'firmado', 'rechazado')),
    constraint nda_envios_token_uniq unique (token)
  )`,
  `create index if not exists nda_envios_row_idx on nda_envios (recruitment_row_id, created_at desc)`,
  `create index if not exists nda_envios_project_idx on nda_envios (project_code, created_at desc)`,
  `create table if not exists nda_eventos (
    id         uuid primary key default gen_random_uuid(),
    n          bigint generated by default as identity,
    envio_id   uuid,
    tipo       text,
    ip         text,
    user_agent text,
    detalle    text,
    actor      text,
    created_at timestamptz not null default now(),
    constraint nda_eventos_tipo_chk ${CHECK_TIPO}
  )`,
  `create index if not exists nda_eventos_envio_idx on nda_eventos (envio_id, created_at)`,
  // Para la base que ya tenía la tabla (el CREATE de arriba no la toca): se amplía la restricción de los tipos. Una sola sentencia, así que nunca queda sin ella.
  `alter table nda_eventos drop constraint if exists nda_eventos_tipo_chk, add constraint nda_eventos_tipo_chk ${CHECK_TIPO}`,
  // La bitácora solo se agrega: cualquier intento de editarla, borrarla o vaciarla truena.
  `create or replace function nda_eventos_inmutable() returns trigger as $$
   begin raise exception 'nda_eventos es una bitácora: no se edita ni se borra'; end;
   $$ language plpgsql`,
  `drop trigger if exists nda_eventos_inmutable_filas on nda_eventos`,
  `create trigger nda_eventos_inmutable_filas before update or delete on nda_eventos for each row execute function nda_eventos_inmutable()`,
  `drop trigger if exists nda_eventos_inmutable_vaciar on nda_eventos`,
  `create trigger nda_eventos_inmutable_vaciar before truncate on nda_eventos for each statement execute function nda_eventos_inmutable()`,
];

async function main() {
  for (const sql of SQL_NDA) await pool.query(sql);

  // updated_at automático en nda_envios, igual que el resto de las tablas (set_updated_at ya existe en la base)
  const fn = await pool.query(`select 1 from pg_proc where proname = 'set_updated_at'`);
  if (fn.rowCount) {
    await pool.query(`drop trigger if exists nda_envios_set_updated on nda_envios`);
    await pool.query(`create trigger nda_envios_set_updated before update on nda_envios for each row execute function set_updated_at()`);
  } else {
    console.warn('⚠ no existe la función set_updated_at: updated_at no se actualizará solo');
  }
  console.log('✅ tablas nda_envios y nda_eventos listas');

  const { error } = await getSupabaseAdmin().storage.createBucket(BUCKET, { public: false });
  if (error && !/already exists/i.test(error.message)) throw error;
  console.log(error ? `ℹ bucket "${BUCKET}" ya existía` : `✅ bucket privado "${BUCKET}" creado`);

  await pool.end();
}

// Solo corre cuando se ejecuta el archivo directo (la prueba lo importa para usar SQL_NDA).
if (process.argv[1]?.endsWith('add-nda-tables.ts')) {
  main().catch(e => { console.error(e); process.exit(1); });
}
